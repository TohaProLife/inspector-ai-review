"""Generate the four T83 DTO modules from canonical local schemas; no runtime stubs."""
from pathlib import Path
import hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
S=ROOT/'packages/contracts/src'
SPECS={
 'matrix-column-pylon-section-run-snapshot':{'entry':'ColumnPylonSectionRunSnapshotEntry','snapshot':'ColumnPylonSectionRunSnapshot'},
 'matrix-column-pylon-section-loader':{'historicalSource':'ColumnPylonSectionHistoricalSource','retainedReview':'ColumnPylonSectionRetainedReview','loaderPackage':'ColumnPylonSectionLoaderPackage'},
 'matrix-column-pylon-section-durable':{'reviewedLoader':'MatrixReviewedLoaderV7'},
 'matrix-column-pylon-section-execution':None,
}
EXTERNAL={
 'document-text-v3.schema.json#/definitions/sourcePath':('DocumentTextV3SourcePath','document-text-v3'),
 'document-text-v3.schema.json#/definitions/nativeBox':('DocumentTextV3NativeBox','document-text-v3'),
 'matrix-steel-execution.schema.json#/definitions/loaderPackage':('SteelComparisonExecutionLoaderPackage','matrix-steel-execution'),
 'matrix-steel-durable.schema.json#/definitions/applicabilitySnapshot':('SteelApplicabilityRunSnapshot','matrix-steel-durable'),
}
for base,names in SPECS.items():
 if names:
  for key,alias in names.items():EXTERNAL[base+'.schema.json#/$defs/'+key]=(alias,base)

def build(base,names):
 src=S/(base+'.schema.json');data=json.loads(src.read_text());defs=data['$defs']
 names=names or {k:'ColumnPylonSectionExecution'+k[0].upper()+k[1:] for k in defs}
 used={}
 def emit(n):
  if n is True:return 'unknown'
  if n is False:return 'never'
  if '$ref' in n:
   ref=n['$ref']
   if ref.startswith('#/'):return names[ref.split('/')[-1]]
   if ref.startswith('matrix-column-pylon-section-v2.schema.json#/'):
    key=ref.split('/')[-1];alias='ColumnPylonSectionV2'+key[0].upper()+key[1:];path='matrix-column-pylon-section-v2'
   else:alias,path=EXTERNAL[ref]
   used[alias]=path;return alias
  if 'const' in n:return json.dumps(n['const'])
  if 'enum' in n:return ' | '.join(json.dumps(v) for v in n['enum'])
  for key,sep in [('oneOf',' | '),('anyOf',' | '),('allOf',' & ')]:
   if key in n and 'type' not in n and 'properties' not in n:return '('+sep.join(emit(v) for v in n[key])+')'
  typ=n.get('type')
  if typ=='null':return 'null'
  if typ in ('integer','number'):return 'number'
  if typ in ('string','boolean'):return typ
  if typ=='array':return '['+', '.join(emit(v) for v in n['prefixItems'])+']' if 'prefixItems' in n else 'Array<'+emit(n.get('items',True))+'>'
  if typ=='object' or 'properties' in n:
   if not n.get('properties'):return 'Record<string, unknown>'
   required=set(n.get('required',n['properties'].keys() if typ is None else []))
   return '{ '+'; '.join(json.dumps(k)+('' if k in required else '?')+': '+emit(v) for k,v in n['properties'].items())+' }'
  raise ValueError(n)
 lines=['export type '+names[k]+' = '+emit(v)+';' for k,v in defs.items()]
 header=['// Generated by scripts/generate-column-pylon-section-execution-contract.py; edit canonical schemas.','// Schema SHA256 '+hashlib.sha256(src.read_bytes()).hexdigest()]
 for path in sorted(set(used.values())):
  header.append('import type { '+', '.join(sorted(k for k,v in used.items() if v==path))+' } from '+json.dumps('./'+path+'.js')+';')
 return '\n'.join(header+lines)+'\n'

if sys.argv[1:] not in ([],['--check']):raise ValueError('Use --check or no args')
for base,names in SPECS.items():
 target=S/(base+'.ts');body=build(base,names)
 if sys.argv[1:]:assert target.read_text()==body,'Stale generated '+str(target)
 else:target.write_text(body)
print(json.dumps({'status':'PASS','generatedModules':len(SPECS),'mode':'check' if sys.argv[1:] else 'generate'}))
