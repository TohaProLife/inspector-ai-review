"""Generate audit DTOs from allowlisted local schemas, without network access."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "packages/contracts/src/document-text-v3-audit.schema.json"
TARGET = ROOT / "packages/contracts/src/document-text-v3-audit.ts"
schema = json.loads(SCHEMA.read_text())
names = {name: "DocumentTextV3Audit" + name[0].upper() + name[1:] for name in schema["definitions"]}
external = {
    "document-text-v3.schema.json#/definitions/extractorProfile": "DocumentTextV3ExtractorProfile",
    "document-text-v3.schema.json#/definitions/artifact": "DocumentTextV3Artifact",
}


def emit(value):
    if "$ref" in value:
        ref = value["$ref"]
        if ref in external:
            return external[ref]
        assert ref.startswith("#/definitions/") and ref.count("/") == 2
        return names[ref.rsplit("/", 1)[1]]
    if "const" in value:
        return json.dumps(value["const"], ensure_ascii=False)
    if "enum" in value:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in value["enum"])
    for combinator, separator in (("allOf", " & "), ("anyOf", " | ")):
        if combinator in value:
            return "(" + separator.join(emit(item) for item in value[combinator]) + ")"
    kind = value["type"]
    if kind in ("string", "null"):
        return kind
    if kind == "integer":
        return "number"
    if kind == "array":
        return "Array<" + emit(value["items"]) + ">"
    if kind == "object":
        if isinstance(value.get("additionalProperties"), dict):
            assert not value.get("properties")
            return "Record<string, " + emit(value["additionalProperties"]) + ">"
        assert value.get("additionalProperties") is False or set(value) == {"type", "required", "properties"}
        return "{ " + "; ".join(json.dumps(key) + ("" if key in value["required"] else "?") + ": " + emit(item)
                                 for key, item in value["properties"].items()) + " }"
    raise ValueError("Unsupported local audit schema construct")


output = "// Generated by scripts/generate-document-text-v3-audit-types.py; edit the canonical schema.\n"
output += "// Schema SHA-256: " + hashlib.sha256(SCHEMA.read_bytes()).hexdigest() + "\n"
output += 'import type { DocumentTextV3Artifact, DocumentTextV3ExtractorProfile } from "./document-text-v3.js";\n\n'
output += "\n".join("export type " + names[name] + " = " + emit(value) + ";\n"
                    for name, value in schema["definitions"].items())
TARGET.write_text(output)
print(json.dumps({"status": "GENERATED", "target": str(TARGET.relative_to(ROOT)), "types": len(names)}))
