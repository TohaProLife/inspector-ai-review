"""Derive TypeScript DTOs from the local canonical v4 JSON Schema. No network."""
from __future__ import annotations
import hashlib,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SCHEMA=ROOT/'packages/contracts/src/document-text-v4.schema.json'
TARGET=ROOT/'packages/contracts/src/document-text-v4.ts'
schema=json.loads(SCHEMA.read_text())
names={name:'DocumentTextV4'+name[0].upper()+name[1:] for name in schema['definitions']}
def emit(value):
 if '$ref' in value:
  reference=value['$ref'];assert reference.startswith('#/definitions/') and reference.count('/')==2
  return names[reference.rsplit('/',1)[1]]
 if 'const' in value:return json.dumps(value['const'],ensure_ascii=False)
 if 'enum' in value:return ' | '.join(json.dumps(x,ensure_ascii=False) for x in value['enum'])
 kind=value['type']
 if kind=='string':return 'string'
 if kind=='integer':return 'number'
 if kind=='object':
  assert value.get('additionalProperties') is False
  return '{ '+ '; '.join(json.dumps(k)+('' if k in value['required'] else '?')+': '+emit(v) for k,v in value['properties'].items())+' }'
 if kind=='array':
  child=emit(value['items']);lo=value.get('minItems');hi=value.get('maxItems')
  if lo is not None and hi is not None and lo>=1 and hi<=4:
   return ' | '.join('['+', '.join(child for _ in range(n))+']' for n in range(lo,hi+1))
  return 'Array<'+child+'>'
 raise ValueError('Unsupported local schema construct')
text='// Generated by scripts/generate-document-text-v4-types.py; edit the canonical schema.\n'
text+='// Schema SHA-256: '+hashlib.sha256(SCHEMA.read_bytes()).hexdigest()+'\n'
text+='// Structural DTOs only; whole native/geometry/quality/profile validation is required.\n\n'
text+='\n'.join('export type '+names[name]+' = '+emit(value)+';\n' for name,value in schema['definitions'].items())
assert sys.argv[1:] in ([], ["--check"]), "Only --check supported"
if sys.argv[1:]:
 assert TARGET.read_text() == text, "Generated v4 types are stale"
else:
 TARGET.write_text(text)
print(json.dumps({'status':'CHECKED' if sys.argv[1:] else 'GENERATED','target':str(TARGET.relative_to(ROOT)),'types':len(names)}))
