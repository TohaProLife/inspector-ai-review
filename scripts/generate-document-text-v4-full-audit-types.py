"""Generate explicit large-audit DTOs from allowlisted local schema, no network."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "packages/contracts/src/document-text-v4-full-audit.schema.json"
TARGET = ROOT / "packages/contracts/src/document-text-v4-full-audit.ts"
schema = json.loads(SCHEMA.read_text())
names = {name: "DocumentTextV4FullAudit" + name[0].upper() + name[1:] for name in schema["definitions"]}
external = {
    "document-text-v4.schema.json#/definitions/extractorProfile": "DocumentTextV4ExtractorProfile",
    "document-text-v4.schema.json#/definitions/artifact": "DocumentTextV4Artifact",
    "document-text-v4.schema.json#/definitions/page": "DocumentTextV4Page",
}
def emit(value):
    if "$ref" in value:
        reference = value["$ref"]
        if reference in external:
            return external[reference]
        assert reference.startswith("#/definitions/") and reference.count("/") == 2
        return names[reference.rsplit("/", 1)[1]]
    if "const" in value:
        return json.dumps(value["const"], ensure_ascii=False)
    if "enum" in value:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in value["enum"])
    for combinator, separator in (("allOf", " & "), ("anyOf", " | "), ("oneOf", " | ")):
        if combinator in value:
            return "(" + separator.join(emit(item) for item in value[combinator]) + ")"
    kind = value["type"]
    if kind in ("string", "null"):
        return kind
    if kind == "integer":
        return "number"
    if kind == "array":
        return "Array<" + emit(value["items"]) + ">"
    if kind == "object":
        additional = value.get("additionalProperties")
        if isinstance(additional, dict):
            assert not value.get("properties")
            return "Record<string, " + emit(additional) + ">"
        if additional is True:
            assert not value.get("properties")
            return "Record<string, unknown>"
        assert additional is False or set(value) == {"type", "required", "properties"}
        required = value.get("required", [])
        return "{ " + "; ".join(json.dumps(key) + ("" if key in required else "?") + ": " + emit(item)
                                 for key, item in value.get("properties", {}).items()) + " }"
    raise ValueError("Unsupported local large-audit schema construct")
output = "// Generated by scripts/generate-document-text-v4-full-audit-types.py; edit the canonical schema.\n"
output += "// Schema SHA-256: " + hashlib.sha256(SCHEMA.read_bytes()).hexdigest() + "\n"
output += 'import type { DocumentTextV4Artifact, DocumentTextV4ExtractorProfile, DocumentTextV4Page } from "./document-text-v4.js";\n\n'
output += "\n".join("export type " + names[name] + " = " + emit(value) + ";\n" for name, value in schema["definitions"].items())
assert sys.argv[1:] in ([], ["--check"]), "Only --check supported"
if sys.argv[1:]:
    assert TARGET.read_text() == output, "Generated large-audit types are stale"
else:
    TARGET.write_text(output)
print(json.dumps({"status": "CHECKED" if sys.argv[1:] else "GENERATED", "target": str(TARGET.relative_to(ROOT)), "types": len(names)}))
