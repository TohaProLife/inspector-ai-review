export type ApiOperationId = (typeof apiOperationContracts)[number]["id"];

function getOperation(id: ApiOperationId): ApiOperationContract {
  const operation = apiOperationContracts.find((candidate) => candidate.id === id);
  if (!operation) throw new Error(`Unknown API operation: ${id}`);
  return operation;
}

function dereferenceSchema(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(dereferenceSchema);
  if (!schema || typeof schema !== "object") return schema;

  const object = schema as Record<string, unknown>;
  if (typeof object.$ref === "string" && object.$ref.startsWith("#/components/schemas/")) {
    const name = object.$ref.slice("#/components/schemas/".length) as ApiSchemaName;
    const target = apiSchemas[name];
    if (!target) throw new Error(`Unknown API schema: ${name}`);
    const siblings = Object.fromEntries(Object.entries(object).filter(([key]) => key !== "$ref"));
    return { ...(dereferenceSchema(target) as Record<string, unknown>), ...siblings };
  }

  return Object.fromEntries(Object.entries(object).map(([key, value]) => [key, dereferenceSchema(value)]));
}

export function fastifySchemaFor(id: ApiOperationId): FastifySchema {
  const operation = getOperation(id);
  const schema: FastifySchema = {
    response: Object.fromEntries(
      Object.entries(operation.responses)
        .filter(([statusCode]) => !operation.binaryResponse || Number(statusCode) >= 400)
        .map(([statusCode, contract]) => [
        statusCode,
        dereferenceSchema(apiSchemas[contract.schema]),
        ]),
    ),
  };
  if (operation.params) schema.params = dereferenceSchema(operation.params);
  if (operation.querystring) schema.querystring = dereferenceSchema(operation.querystring);
  if (operation.bodySchema && operation.validateBody !== false) {
    schema.body = dereferenceSchema(apiSchemas[operation.bodySchema]);
  }
  return schema;
}

function parametersFor(location: "path" | "query", schema?: JsonSchema): Array<Record<string, unknown>> {
  if (!schema) return [];
  const properties = (schema.properties ?? {}) as Record<string, JsonSchema>;
  const required = new Set((schema.required ?? []) as string[]);
  return Object.entries(properties).map(([name, propertySchema]) => ({
    name,
    in: location,
    required: location === "path" || required.has(name),
    schema: propertySchema,
  }));
}

export function buildOpenApiPaths(): Record<string, Record<string, unknown>> {
  const paths: Record<string, Record<string, unknown>> = {};
  const operations: readonly ApiOperationContract[] = apiOperationContracts;

  for (const operation of operations) {
    const requestSchema = operation.bodySchema ? ref(operation.bodySchema) : operation.multipartBody;
    const requestContentType = operation.multipartBody ? "multipart/form-data" : "application/json";
    const parameters = [
      ...parametersFor("path", operation.params),
      ...parametersFor("query", operation.querystring),
      ...(operation.openApiHeaders ?? []).map((header) => ({
        name: header.name,
        in: "header",
        required: header.required,
        description: header.description,
        schema: header.schema,
      })),
    ];
    const openApiOperation: Record<string, unknown> = {
      operationId: operation.id,
      summary: operation.summary,
      parameters,
      security: operation.security,
      responses: Object.fromEntries(
        Object.entries(operation.responses).map(([statusCode, contract]) => [
          statusCode,
          {
            description: contract.description,
            headers: contract.headers,
            content: {
              [contract.contentType ?? "application/json"]: { schema: ref(contract.schema) },
            },
          },
        ]),
      ),
    };
    if (requestSchema) {
      openApiOperation.requestBody = {
        required: true,
        content: { [requestContentType]: { schema: requestSchema } },
      };
    }
    (paths[operation.openApiPath] ??= {})[operation.method] = openApiOperation;
  }

  return paths;
}
